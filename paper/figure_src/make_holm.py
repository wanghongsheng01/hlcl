"""Holm adjustment across all settings for the paired comparisons reported in the paper.
Back-calculates z = mean / (half-width / 1.96) from the Nadeau-Bengio intervals in numbers.tex
(normal approximation, as in code/make_tables.py) and writes tables/holm.tex (macros)."""
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
nums = (ROOT / "tables" / "numbers.tex").read_text()
SET = [("dbpedia", ["0.01", "0.02", "0.05", "0.1"]), ("wos", ["0.1", "0.15", "0.2", "0.3"]),
       ("bgc", ["0.02", "0.05", "0.1", "0.15"]), ("bgc_haiku", ["0.02", "0.05", "0.1", "0.15"]),
       ("bgc_gpt", ["0.02", "0.05", "0.1", "0.15"]),
       ("amazon", ["0.02", "0.05", "0.1", "0.15"])]


def md(key):
    s = re.search(r"\\csname " + re.escape(key) + r"\\endcsname\{([^}]*)\}", nums).group(1)
    m, h = map(float, re.match(r"([+-][0-9.]+)\$\\pm\$([0-9.]+)", s).groups())
    return m, h


def holm(items, good_sign):
    """items: list of (name, mean, halfwidth). Returns (#significant favourable, #significant unfavourable)."""
    ps = []
    for name, m, h in items:
        z = m / (h / 1.96) if h > 0 else (0.0 if m == 0 else math.inf)
        p = math.erfc(abs(z) / math.sqrt(2))
        ps.append((p, name, m))
    ps.sort()
    k = len(ps)
    good = bad = 0
    names = []
    for i, (p, name, m) in enumerate(ps):
        if p * (k - i) > 0.05:
            break
        if (m > 0) == good_sign:
            good += 1
        else:
            bad += 1
        names.append(name)
    return good, bad, names


out = []
best = [(f"{k}@{a}", *md(f"r@{k}@{a}@best@dif")) for k, al in SET for a in al]
g, b, n = holm(best, good_sign=False)
out += [("s@holm@best@wins", g), ("s@holm@best@losses", b)]
print("best baseline effort (Holm):", g, b, n)
for kind, sign in (("power", True), ("effort", False)):
    it = [(f"{k}@{a}", *md(f"d@{k}@{a}@ItemBest@{kind}")) for k, al in SET for a in al]
    g, b, n = holm(it, good_sign=sign)
    out += [(f"s@holm@item@{kind}@better", g), (f"s@holm@item@{kind}@worse", b)]
    print("Item-cert.*", kind, "(Holm):", g, b, n)
(ROOT / "tables" / "holm.tex").write_text("% generated by figure_src/make_holm.py from numbers.tex\n" + "\n".join(
    f"\\expandafter\\def\\csname {k}\\endcsname{{{v}}}" for k, v in out) + "\n")
