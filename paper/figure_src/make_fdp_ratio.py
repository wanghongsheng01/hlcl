"""Mean realized test-split FDP of HLCL divided by alpha, per setting, from the released
per-split results (hlcl-code/results/v9_*.json). Writes tables/fdpratio.tex (min/max macros)."""
import json
from pathlib import Path

import numpy as np

# the code repository is either the parent of this paper folder (paper/ inside the
# repository) or its sibling hlcl-code/ (separate working copy)
_P = Path(__file__).resolve().parents[1]
CODE = _P.parent if (_P.parent / "results").is_dir() else _P.parent / "hlcl-code"
ROOT = _P
RES = CODE / "results"
vals = {}
for k in ("dbpedia", "wos", "bgc", "bgc_haiku", "bgc_gpt", "amazon"):
    runs = json.loads((RES / f"v9_{k}.json").read_text())["runs"]
    for a in sorted({r["alpha"] for r in runs}):
        f = [r["HLCL"]["fdp"] for r in runs if r["alpha"] == a]
        vals[(k, a)] = float(np.mean(f)) / a
lo, hi = min(vals.values()), max(vals.values())
print({f"{k}@{a}": round(v, 2) for (k, a), v in vals.items()})
(ROOT / "tables" / "fdpratio.tex").write_text(
    "% generated by figure_src/make_fdp_ratio.py from the released per-split result files\n"
    f"\\expandafter\\def\\csname s@fdpratio@HLCL@min\\endcsname{{{lo:.2f}}}\n"
    f"\\expandafter\\def\\csname s@fdpratio@HLCL@max\\endcsname{{{hi:.2f}}}\n")
print(lo, hi)
