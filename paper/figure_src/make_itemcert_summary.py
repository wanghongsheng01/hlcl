"""Summarize the Nadeau-Bengio-corrected paired differences HLCL - Item-cert.* (power and
effort) over all settings and write tables/itemcert.tex (macros) and tables/itemcert_table.tex.
Reads only tables/numbers.tex, which code/make_tables.py generates from the per-split results."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
nums = (ROOT / "tables" / "numbers.tex").read_text()
SET = [("dbpedia", "DBPedia (A)", ["0.01", "0.02", "0.05", "0.1"]), ("wos", "WOS-46985 (A)", ["0.1", "0.15", "0.2", "0.3"]),
       ("bgc", "Blurb (A)", ["0.02", "0.05", "0.1", "0.15"]), ("bgc_haiku", "Blurb (B)", ["0.02", "0.05", "0.1", "0.15"]),
       ("bgc_gpt", "Blurb (C)", ["0.02", "0.05", "0.1", "0.15"]),
       ("amazon", "Amazon (A)", ["0.02", "0.05", "0.1", "0.15"])]


def d(key):
    s = re.search(r"\\csname " + re.escape(key) + r"\\endcsname\{([^}]*)\}", nums).group(1)
    m, h = re.match(r"([+-][0-9.]+)\$\\pm\$([0-9.]+)", s).groups()
    return float(m), float(h), s


cnt = {"power": [0, 0, 0], "effort": [0, 0, 0]}   # HLCL better, worse, tie
rows = []
for key, name, alphas in SET:
    for a in alphas:
        r = [name if a == alphas[0] else "", a]
        for k in ("power", "effort"):
            m, h, s = d(f"d@{key}@{a}@ItemBest@{k}")
            better = (m - h > 0) if k == "power" else (m + h < 0)
            worse = (m + h < 0) if k == "power" else (m - h > 0)
            cnt[k][0 if better else 1 if worse else 2] += 1
            r.append(("\\textbf{" + s + "}") if better else s)
        rows.append(" & ".join(r) + " \\\\")
mac = []
for k in cnt:
    for i, lab in enumerate(["better", "worse", "tie"]):
        mac.append(f"\\expandafter\\def\\csname s@item@{k}@{lab}\\endcsname{{{cnt[k][i]}}}")
(ROOT / "tables" / "itemcert.tex").write_text("% generated by figure_src/make_itemcert_summary.py from numbers.tex\n" + "\n".join(mac) + "\n")
tab = ["\\begin{tabular}{llcc}", "\\toprule", "Setting & $\\alpha$ & power & effort \\\\", "\\midrule"]
for i, r in enumerate(rows):
    if i and i % 4 == 0:
        tab.append("\\midrule")
    tab.append(r)
tab += ["\\bottomrule", "\\end{tabular}"]
(ROOT / "tables" / "itemcert_table.tex").write_text("% generated by figure_src/make_itemcert_summary.py from numbers.tex\n" + "\n".join(tab) + "\n")
print(cnt)
