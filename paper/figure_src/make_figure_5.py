"""Figure 5: paired effort difference HLCL - strongest valid certified baseline, with
Nadeau-Bengio-corrected 95% intervals, for all settings.

Reads ../tables/numbers.tex (generated by code/make_tables.py from the released per-split
results), so the figure shows exactly the values quoted in the text.
Run:  python3 make_figure_5.py   -> ../figures/Figure_5.pdf
"""
import re
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
nums = (ROOT / "tables" / "numbers.tex").read_text()
plt.rcParams.update({"font.size": 8, "font.family": "sans-serif", "font.sans-serif": ["Arial", "Helvetica", "DejaVu Sans"], "mathtext.fontset": "dejavuserif",
                     "pdf.fonttype": 42, "mathtext.fontset": "custom", "mathtext.rm": "Arial",
                     "mathtext.it": "Arial:italic", "mathtext.bf": "Arial:bold", "axes.linewidth": 0.6})

SETTINGS = [("dbpedia", "DBPedia (A)", ["0.01", "0.02", "0.05", "0.1"]),
            ("wos", "WOS-46985 (A)", ["0.1", "0.15", "0.2", "0.3"]),
            ("bgc", "Blurb (A)", ["0.02", "0.05", "0.1", "0.15"]),
            ("bgc_haiku", "Blurb (B)", ["0.02", "0.05", "0.1", "0.15"]),
            ("bgc_gpt", "Blurb (C)", ["0.02", "0.05", "0.1", "0.15"]),
            ("amazon", "Amazon (A)", ["0.02", "0.05", "0.1", "0.15"])]
MARK = {"Item-cert.": ("s", "#d1495b"), "HSC": ("P", "#00798c"), "Per-field": ("D", "#66a182")}


def get(key):
    m = re.search(r"\\csname " + re.escape(key) + r"\\endcsname\{([^}]*)\}", nums)
    if not m:
        raise KeyError(key)
    return m.group(1)


rows = []
for key, name, alphas in SETTINGS:
    for a in alphas:
        d, h = re.match(r"([+-][0-9.]+)\$\\pm\$([0-9.]+)", get(f"r@{key}@{a}@best@dif")).groups()
        rows.append((f"{name}, $\\alpha$={a}", float(d), float(h), get(f"r@{key}@{a}@best@name")))

fig, ax = plt.subplots(figsize=(3.6, 0.22 * len(rows) + 0.0))
for i, (lab, d, h, base) in enumerate(rows):
    y = len(rows) - 1 - i
    mk, col = MARK[base]
    cls = "#1b6ca8" if d + h < 0 else ("#b23a48" if d - h > 0 else "#7a7a7a")
    ax.plot([d - h, d + h], [y, y], color=cls, lw=1.4, solid_capstyle="butt")
    ax.plot(d, y, marker=mk, color=col, ms=4.2, mec="black", mew=0.4, ls="none")
ax.axvline(0, color="black", lw=0.6, ls="--")
ax.set_yticks(range(len(rows)))
ax.set_yticklabels([r[0] for r in rows][::-1], fontsize=8)
ax.set_xlabel("effort difference, HLCL $-$ baseline")
for g in range(1, len(SETTINGS)):
    ax.axhline(len(rows) - 4 * g - 0.5, color="#cccccc", lw=0.5)
handles = [plt.Line2D([], [], marker=MARK[b][0], color=MARK[b][1], mec="black", mew=0.4, ls="none", ms=4.2,
                      label=b.replace("Item-cert.", "Item-cert.*"))
           for b in MARK]
handles += [plt.Line2D([], [], color=c, lw=1.4, label=l) for c, l in
            [("#1b6ca8", "HLCL significantly cheaper"), ("#b23a48", "HLCL significantly costlier"),
             ("#7a7a7a", "not significant")]]
ax.legend(handles=handles, loc="upper center", bbox_to_anchor=(0.42, -0.1), ncol=2, frameon=False, fontsize=8,
          handletextpad=0.4, columnspacing=1.0)
ax.set_ylim(-0.6, len(rows) - 0.4)
fig.savefig(ROOT / "figures" / "Figure_5.pdf", bbox_inches="tight", pad_inches=0.02)
fig.savefig(Path(__file__).with_name("Figure_5_preview.png"), dpi=170, bbox_inches="tight", pad_inches=0.02)
wins = sum(d + h < 0 for _, d, h, _ in rows)
losses = sum(d - h > 0 for _, d, h, _ in rows)
print(f"wrote Figure_5.pdf: {len(rows)} settings, {wins} wins, {losses} losses, {len(rows) - wins - losses} ties")
